    
"""
Pydantic request and response schemas for BRAG chatbots.

Schemas define the public API contract without exposing
internal database identifiers or ORM implementation details.
"""

from datetime import datetime

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    field_validator
    )


class ChatbotCreateRequest(BaseModel):
    """Validate the request for creating a chatbot."""

    name: str = Field(
        ...,
        min_length=1,
        max_length=100,
        description="Human-readable chatbot name.",
    )

    description: str | None = Field(
        default=None,
        max_length=500,
        description="Optional chatbot description.",
    )


class ChatbotResponse(BaseModel):
    """Represent a chatbot in an API response."""

    model_config = ConfigDict(from_attributes=True)

    chatbot_id: str
    name: str
    description: str | None
    is_active: bool
    created_at: datetime
    updated_at: datetime



class ChatbotQueryRequest(BaseModel):
    """Validate a question submitted to a specific chatbot."""

    question: str = Field(
        ...,
        min_length=1,
        max_length=4000,
        description="Question to ask the chatbot.",
    )

    @field_validator("question")
    @classmethod
    def validate_question(cls, value: str) -> str:
        """Remove surrounding whitespace and reject empty questions."""

        question = value.strip()

        if not question:
            raise ValueError(
                "Question cannot be empty."
            )

        return question


class ChatbotQueryResponse(BaseModel):
    """Represent an answer generated by a specific chatbot."""

    chatbot_id: str
    answer: str
