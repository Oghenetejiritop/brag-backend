
"""
Repository for persistent BRAG user records.

This module isolates user-related database operations from
application services and API routes.
"""

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.db.models.user import User


class UserRepository:
    """
    Provides persistence operations for BRAG users.

    The repository receives an existing SQLAlchemy Session instead
    of creating its own session. This keeps transaction and session
    lifecycle management outside the repository.
    """

    def __init__(
        self,
        database_session: Session,
    ) -> None:
        """
        Initialize the user repository.

        Args:
            database_session:
                Active SQLAlchemy session used for database operations.
        """

        self._database_session = database_session

    def create_user(self) -> User:
        """
        Create and persist a new BRAG user.

        The public user_id is generated by the User model.

        Returns:
            Newly persisted User instance.
        """

        user = User()

        self._database_session.add(user)

        try:
            # Commit the transaction so database-generated values and
            # model defaults are persisted before returning the user.
            self._database_session.commit()

            # Refresh ensures the returned model reflects the values
            # currently stored in the database.
            self._database_session.refresh(user)

        except Exception:
            # A failed transaction leaves the Session requiring a
            # rollback before it can safely be reused.
            self._database_session.rollback()
            raise

        return user

    def get_by_id(
        self,
        user_id: int,
    ) -> User | None:
        """
        Retrieve a user by the internal database primary key.

        Args:
            user_id:
                Internal integer primary key.

        Returns:
            Matching User or None when no record exists.
        """

        return self._database_session.get(
            User,
            user_id,
        )

    def get_by_user_id(
        self,
        public_user_id: str,
    ) -> User | None:
        """
        Retrieve a user by the public UUID identifier.

        Args:
            public_user_id:
                Public user identifier used by BRAG services.

        Returns:
            Matching User or None when no record exists.
        """

        statement = select(User).where(
            User.user_id == public_user_id
        )

        return self._database_session.scalar(
            statement
        )
